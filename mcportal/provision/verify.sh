#!/usr/bin/env bash
# Minecraft Family Portal - acceptance test of the installed server (read only, changes nothing).
#
#   sudo bash provision/verify.sh [--conf FILE] [--laravel HTTP-CODE]
#
# Checks the installation the unit points to: both services, console, player port, every pack from packs.list
# (installed version = repo version, reported at the last start, no script/content errors since then), portal and
# update check, Laravel, rights (nothing world-writable, nothing root), portal access to the server files.
# --conf: also require that the unit points to MC_DIR/MC_USER from server.conf (after the cut-over).
# --laravel: the HTTP code Laravel gave before (e.g. from setup.sh) - must be the same now.
# Without sudo (as the Minecraft user) the root-only checks are skipped. Exit code 1 if anything failed.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
PORTAL=http://127.0.0.1:8080

CONF_ARG="" LARAVEL_EXPECT=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --conf) CONF_ARG="${2:-}"; shift ;;
    --laravel) LARAVEL_EXPECT="${2:-}"; shift ;;
    *) echo "Aufruf: sudo bash $0 [--conf DATEI] [--laravel HTTP-CODE]"; exit 2 ;;
  esac
  shift
done

FAILED=0
ok()   { printf '    \033[1;32mOK\033[0m      %s\n' "$*"; }
bad()  { printf '    \033[1;31mFEHLER\033[0m  %s\n' "$*"; FAILED=$((FAILED + 1)); }
note() { printf '    \033[1;33mHINWEIS\033[0m %s\n' "$*"; }
check() { local what="$1"; shift; if "$@" >/dev/null 2>&1; then ok "$what"; else bad "$what"; fi; }

U_DIR="$(systemctl show -p WorkingDirectory --value "$UNIT")"
U_USER="$(systemctl show -p User --value "$UNIT")"
ROOT=0; [[ "$(id -u)" == 0 ]] && ROOT=1
[[ $ROOT == 1 || "$(id -un)" == "$U_USER" ]] || fail "Bitte mit sudo ausführen (oder als $U_USER)"

# ---------------------------------------------------------------------------
step "Dienste"
check "$UNIT aktiv" systemctl is-active --quiet "$UNIT"
check "mcportal.service aktiv" systemctl is-active --quiet mcportal.service
check "Konsole (minecraft-bedrock.socket) aktiv" systemctl is-active --quiet minecraft-bedrock.socket
info "Unit: $U_DIR (Benutzer $U_USER)"
if [[ -n "$CONF_ARG" ]]; then
  load_conf "$CONF_ARG"
  [[ "$U_DIR" == "$MC_DIR" ]] && ok "Unit zeigt auf $MC_DIR" || bad "Unit zeigt auf $U_DIR statt $MC_DIR"
  [[ "$U_USER" == "$MC_USER" ]] && ok "läuft als $MC_USER" || bad "läuft als $U_USER statt $MC_USER"
fi
[[ "$U_USER" != root && -n "$U_USER" ]] && ok "Minecraft läuft nicht als root" || bad "Minecraft läuft als root"
PORT="$(sed -n 's/^server-port=//p' "$U_DIR/server.properties")"
if ss -Htuln "sport = :$PORT" | grep -q .; then ok "Spieler-Port $PORT offen"; else bad "Spieler-Port $PORT nicht offen"; fi

# ---------------------------------------------------------------------------
step "Spielregeln (gamerules.list)"
# a query through the console ("gamerule <rule>") reads the rule from the running world, it changes nothing
while read -r rule value; do
  if line="$(console /run/minecraft-bedrock/console "$UNIT" "gamerule $rule" "] $rule = ")"; then
    have="${line##* = }"
    [[ "$have" == "$value" ]] && ok "$rule = $value" || bad "$rule = $have (soll $value) – in der Konsole: gamerule $rule $value"
  else
    bad "$rule: keine Antwort über die Konsole"
  fi
done < <(gamerule_lines)

# ---------------------------------------------------------------------------
step "Packs (Stand des letzten Starts)"
LEVEL="$(sed -n 's/^level-name=//p' "$U_DIR/server.properties")"
WORLD="$U_DIR/worlds/$LEVEL"
INVOCATION="$(systemctl show -p InvocationID --value "$UNIT")"
LOG=""
[[ -n "$INVOCATION" ]] && LOG="$(journalctl -q -o cat --no-pager _SYSTEMD_INVOCATION_ID="$INVOCATION" 2>/dev/null || true)"
[[ -n "$LOG" ]] || bad "kein Log des laufenden Servers lesbar (journalctl)"
while read -r kind pack; do
  src="$PACKS_SRC/$pack/manifest.json" dst="$WORLD/${kind}_packs/$pack/manifest.json"
  want="$(manifest "$src" version)"
  if [[ ! -f "$dst" ]]; then bad "$pack fehlt in der Welt"; continue; fi
  have="$(manifest "$dst" version)"
  if [[ "$have" != "$want" ]]; then bad "$pack: Welt $have, Repo $want"; continue; fi
  if ! grep -q "$(manifest "$src" uuid)" "$WORLD/world_${kind}_packs.json" 2>/dev/null; then
    bad "$pack $have nicht in world_${kind}_packs.json"; continue
  fi
  if [[ "$kind" == behavior ]]; then
    missing=""
    while read -r pat; do grep -aq -- "$pat" <<<"$LOG" || missing="$pat"; done < <(pack_log_patterns "$WORLD/${kind}_packs/$pack")
    if [[ -n "$missing" ]]; then bad "$pack $have hat sich beim letzten Start nicht gemeldet ($missing)"; continue; fi
    ok "$pack $have aktiv"
  else
    ok "$pack $have eingetragen"
  fi
done < <(pack_lines)
# errors from scripts and pack content count; Mojang's own messages about an old world (biomes, structures,
# features generated by earlier versions) are only shown
ERRORS="$(log_errors <<<"$LOG")"
OURS="$(grep -aE '\[Scripting\]|\[Json|\[Item|\[Texture|\[Recipes\]|mcfs|mcportal' <<<"$ERRORS" || true)"
OTHER="$(grep -avE '\[Scripting\]|\[Json|\[Item|\[Texture|\[Recipes\]|mcfs|mcportal' <<<"$ERRORS" | grep -a . || true)"
if [[ -z "$OURS" ]]; then ok "keine Script-/Pack-Fehler seit dem letzten Start"
else bad "$(wc -l <<<"$OURS") Script-/Pack-Fehler seit dem letzten Start:"; sed 's/^/              /' <<<"$OURS" | head -10; fi
if [[ -n "$OTHER" ]]; then
  note "$(wc -l <<<"$OTHER") Meldungen von Minecraft selbst (nicht von unseren Packs):"
  cut -c1-160 <<<"$OTHER" | sort -u -t']' -k2 | head -5 | sed 's/^/              /'
fi

# ---------------------------------------------------------------------------
step "Portal"
STATUS="$(curl -s -m 10 "$PORTAL/api/status" || true)"
if python3 -I -c 'import json,sys; d=json.loads(sys.argv[1]); assert d["active_state"]=="active" and d["console_available"]' "$STATUS" 2>/dev/null
then ok "Portal antwortet, sieht den Server und die Konsole"; else bad "Portal: /api/status nicht wie erwartet"; fi
UPD="$(curl -s -m 40 -X POST "$PORTAL/api/update/check" || true)"
if VERS="$(python3 -I -c 'import json,sys; d=json.loads(sys.argv[1]); assert d["latest"] and not d["check_error"]; print("läuft", d["current"], "- neueste", d["latest"])' "$UPD" 2>/dev/null)"
then ok "Update-Prüfung geht ($VERS)"
else bad "Update-Prüfung fehlgeschlagen"; fi
LARAVEL="$(curl -s -o /dev/null -m 10 -w '%{http_code}' http://127.0.0.1/ || true)"
if [[ -z "$LARAVEL_EXPECT" ]]; then info "Laravel: HTTP $LARAVEL (Vergleich mit --laravel CODE)"
elif [[ "$LARAVEL" == "$LARAVEL_EXPECT" ]]; then ok "Laravel antwortet wie vorher (HTTP $LARAVEL)"
else bad "Laravel: HTTP $LARAVEL, vorher $LARAVEL_EXPECT"; fi

# ---------------------------------------------------------------------------
step "Rechte"
WW="$(find "$U_DIR" ! -type l -perm -o+w 2>/dev/null | wc -l)"
RO="$(find "$U_DIR" ! -user "$U_USER" 2>/dev/null | wc -l)"
[[ "$WW" == 0 ]] && ok "nichts unter $U_DIR für alle schreibbar" || bad "$WW Einträge unter $U_DIR für alle schreibbar"
[[ "$RO" == 0 ]] && ok "alles unter $U_DIR gehört $U_USER" || bad "$RO Einträge unter $U_DIR gehören nicht $U_USER"
if [[ $ROOT == 1 ]]; then
  check "Portal liest server.properties" runuser -u mcportal -- test -r "$U_DIR/server.properties"
  check "Portal schreibt allowlist.json" runuser -u mcportal -- test -w "$U_DIR/allowlist.json"
  check "Portal schreibt permissions.json" runuser -u mcportal -- test -w "$U_DIR/permissions.json"
  check "Portal liest die Welt (Karte, Seed)" runuser -u mcportal -- test -r "$WORLD/level.dat" -a -r "$WORLD/db/CURRENT"
else
  note "Zugriff des Portals auf die Serverdateien nur mit sudo prüfbar"
fi

# ---------------------------------------------------------------------------
if [[ $FAILED == 0 ]]; then printf '\n\033[1;32mAlles in Ordnung.\033[0m\n'
else printf '\n\033[1;31m%s Prüfung(en) fehlgeschlagen.\033[0m\n' "$FAILED"; exit 1; fi
